#!/usr/bin/env python3
"""Create the local release-signing keystore (DEC-25).

Why this exists: the deliverable must install with `adb install -r`, which only
works if consecutive builds are signed with the *same* key. The key must not live
in version control, so each machine generates its own and Gradle reads the
credentials from a git-ignored `keystore.properties`.

Behaviour:
  * refuses to overwrite an existing keystore unless --force is given
  * generates a random password (the operator never has to invent one)
  * writes android/keystore.properties with 0600 permissions where the OS supports it
  * never prints the password value

Usage:
    python tools/make_dev_keystore.py [--force] [--alias dashcue]
"""

from __future__ import annotations

import argparse
import os
import secrets
import shutil
import string
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
KEYSTORE_PATH = REPO_ROOT / "android" / "keystore" / "dashcue-release.jks"
PROPS_PATH = REPO_ROOT / "android" / "keystore.properties"

DNAME = "CN=DashCue Local Release, OU=Development, O=DashCue, C=US"


def random_password(length: int = 32) -> str:
    # keytool reads the password from stdin; restrict to characters that survive
    # being written into a Java properties file without escaping.
    alphabet = string.ascii_letters + string.digits
    return "".join(secrets.choice(alphabet) for _ in range(length))


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the DashCue release keystore")
    parser.add_argument("--force", action="store_true", help="overwrite an existing keystore")
    parser.add_argument("--alias", default="dashcue", help="key alias (default: dashcue)")
    args = parser.parse_args()

    if KEYSTORE_PATH.exists() and not args.force:
        print(f"refusing to overwrite {KEYSTORE_PATH.relative_to(REPO_ROOT)} (use --force)")
        return 1

    keytool = shutil.which("keytool")
    if not keytool:
        print("keytool not found on PATH.")
        print("Install a JDK 17 (Temurin recommended) and re-run, or run keytool from")
        print(f"  {Path(os.environ.get('JAVA_HOME', '')) / 'bin'}")
        return 1

    KEYSTORE_PATH.parent.mkdir(parents=True, exist_ok=True)
    store_pass = random_password()
    key_pass = store_pass  # one password keeps the operator's workflow simple

    cmd = [
        keytool,
        "-genkeypair",
        "-keystore", str(KEYSTORE_PATH),
        "-alias", args.alias,
        "-keyalg", "RSA",
        "-keysize", "4096",
        "-validity", "10000",
        "-storetype", "PKCS12",
        "-dname", DNAME,
    ]
    proc = subprocess.run(
        cmd,
        input=f"{store_pass}\n{store_pass}\n",
        capture_output=True,
        text=True,
        check=False,
    )
    if proc.returncode != 0:
        print("keytool failed:")
        print((proc.stderr or proc.stdout).strip())
        return 1

    PROPS_PATH.write_text(
        "# DashCue local release signing (DEC-25). GIT-IGNORED - never commit.\n"
        "# Generated by tools/make_dev_keystore.py on this machine.\n"
        f"storeFile=keystore/{KEYSTORE_PATH.name}\n"
        f"storePassword={store_pass}\n"
        f"keyAlias={args.alias}\n"
        f"keyPassword={key_pass}\n",
        encoding="utf-8",
    )
    try:
        # Best effort: on Windows the ACL model differs and chmod is a no-op.
        os.chmod(PROPS_PATH, 0o600)
    except OSError:
        pass

    print(f"keystore : {KEYSTORE_PATH.relative_to(REPO_ROOT)}")
    print(f"properties: {PROPS_PATH.relative_to(REPO_ROOT)} (password not printed)")
    print()
    print("Reminder: every future upgrade must be signed with THIS key, otherwise")
    print("`adb install -r` fails with INSTALL_FAILED_UPDATE_INCOMPATIBLE and the app")
    print("must be uninstalled first (which discards its data).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
